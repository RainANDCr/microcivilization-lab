  w.settlements=[{id:100001,name:'家园',x,y,founded:0,members:[1,2],food:50,wood:0,buildings:[{type:'housing',progress:24,cost:12}],knowledge:0,technology:[]}];
  w.families=[{id:200001,name:'家庭 1',settlement:100001,parents:[1,2],members:[1,2],founded:0,lastBirth:0}];
  updatePopulation(w);w.tick=2172;w.settlements[0].food=0;w.agents[1].food=2;
  Object.assign(w.agents[2],{food:0,hunger:99,health:1});w.tiles.forEach(t=>{t.food=0;});
