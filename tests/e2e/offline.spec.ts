test('preserves archived ancestors, resources and a birth beyond the old historical cap',async({page})=>{
  const w=historyWorld();updatePopulation(w);
  await page.goto('/');
  await page.locator('#file').setInputFiles({name:'history.mcworld',mimeType:'application/json',buffer:Buffer.from(serializeArchive(w))});
  await expect(page.locator('#engine-label')).toContainText('0.4.0');
  await expect(page.locator('#families')).toContainText('先人 3');
  await expect(page.locator('#families')).toContainText('先人 4');
  await expect(page.locator('#families')).toContainText('新生 2001');
  await expect(page.locator('#families')).toContainText('离世 1998 人');
  await page.getByRole('button',{name:'单步推进'}).click();await expect(page.locator('#tick')).toHaveText('28,081');
  await page.getByRole('button',{name:'保存',exact:true}).click();await expect(page.locator('#toast')).toContainText('已保存');
  await page.reload();await page.getByRole('button',{name:/本地存档/}).click();await page.getByRole('button',{name:/打开 ↗/}).click();
  await expect(page.locator('#families')).toContainText('先人 3');await expect(page.locator('#tick')).toHaveText('28,081');
  const downloading=page.waitForEvent('download');await page.getByRole('button',{name:'导出',exact:true}).click();
  const download=await downloading,path=await download.path();expect(path).toBeTruthy();
  const restored=parseArchive(await readFile(path!,'utf8'));
  expect(restored.version).toBe(3);expect(restored.deceased).toHaveLength(1998);
  expect(restored.agents.some(a=>a.id===2001)).toBe(true);
  expect(restored.deceased!.find(a=>a.id===3)?.food).toBe(1);expect(restored.deceased!.find(a=>a.id===3)?.wood).toBe(1);
});

